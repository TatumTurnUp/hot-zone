START, END = '<!-- TECH-STATS:2026:START -->', '<!-- TECH-STATS:2026:END -->'

def fname(p): return re.sub(r'[\\/:*?"<>|]', '', p['name']).strip()
def fa(v): return '—' if v is None else (f'{v:.3f}'.lstrip('0') if isinstance(v, float) and v < 1 else str(v))
def pct(v): return '—' if v is None else f'{v*100:.1f}%'
def jdump(o): return json.dumps(o, separators=(',', ':'), ensure_ascii=False)

def csv_block(rows, cols):
    out = [','.join(cols)]
    for r in rows:
        out.append(','.join('' if r.get(c) is None else str(r.get(c)).replace(',', ';') for c in cols))
    return '\n'.join(out)

def tech_atl(p):
    parts = [START, '## Technical Stats — 2026', '',
             '> Machine-readable block for agents/infographics. Regenerated by the pipeline after every game — do not hand-edit between the markers.',
             f'> Full detail (pitch-level heat grids, spray coordinates, movement points): `Data/players/{p["id"]}.json`. Units: rates are 0–1 decimals, velo mph, movement inches, spray coordinates feet from home plate (x = toward 1B side), plate_x/plate_z feet (catcher view).', '']
    if 'hitting' in p:
        h = p['hitting']
        summary = {'season': h['season'], 'sabermetrics': h.get('sabermetrics'), 'statcast': h.get('statcast'), 'statcast_vs': h.get('statcast_vs'),
                   'bat_tracking_leaderboard': p.get('bat_tracking_lb'), 'swing_take': p.get('swing_take'), 'percentiles': p['percentiles'].get('batting'),
                   'sprint': p['running'].get('sprint'), 'splits': h.get('splits'), 'postseason': h.get('postseason')}
        parts += ['### hitting.summary', '```json', jdump(summary), '```', '',
                  '### hitting.zones (Statcast zones 1–9 in-zone, 11–14 shadow; catcher view)', '```json', jdump(h.get('zones')), '```', '',
                  '### hitting.vs_pitch_type', '```json', jdump(h.get('vs_pitch_type')), '```', '',
                  '### hitting.counts (pitch-level by count; pa_end = PAs ending in that count)', '```json', jdump(h.get('counts')), '```', '']
        gl = []
        cum = {r['date']: r for r in h.get('cumulative', [])}; rl = {r['date']: r for r in h.get('rolling_15g', [])}
        for g in h['gamelog']:
            sc = g.get('sc') or {}
            gl.append({'date': g['date'], 'gt': g['gt'], 'opp': g['opp'], 'home': int(bool(g['home'])), 'win': int(bool(g.get('win'))), 'pa': g.get('plateAppearances'), 'ab': g.get('atBats'),
                       'h': g.get('hits'), '2b': g.get('doubles'), '3b': g.get('triples'), 'hr': g.get('homeRuns'), 'r': g.get('runs'), 'rbi': g.get('rbi'), 'bb': g.get('baseOnBalls'),
                       'k': g.get('strikeOuts'), 'sb': g.get('stolenBases'), 'pitches': sc.get('pitches'), 'swings': sc.get('swings'), 'whiffs': sc.get('whiffs'), 'bip': sc.get('bip'),
                       'avg_ev': sc.get('avg_ev'), 'max_ev': sc.get('max_ev'), 'hard': sc.get('hard'), 'barrels': sc.get('barrels'), 'xwoba_num': sc.get('xwoba_num'), 'woba_den': sc.get('woba_den'),
                       'bat_speed': sc.get('bat_speed'),
                       'cum_avg': cum.get(g['date'], {}).get('avg') if g['gt'] == 'R' else None, 'cum_ops': cum.get(g['date'], {}).get('ops') if g['gt'] == 'R' else None,
                       'cum_xwoba': cum.get(g['date'], {}).get('xwoba') if g['gt'] == 'R' else None, 'r15_ops': rl.get(g['date'], {}).get('ops') if g['gt'] == 'R' else None,
                       'r15_xwoba': rl.get(g['date'], {}).get('xwoba') if g['gt'] == 'R' else None})
        parts += ['### hitting.gamelog (one row per game; gt R=regular P=postseason; cum_* = season-to-date; r15_* = rolling 15 games)', '```csv',
                  csv_block(gl, list(gl[0].keys()) if gl else []), '```', '']
    if 'pitching' in p:
        P = p['pitching']
        summary = {'season': P['season'], 'sabermetrics': P.get('sabermetrics'), 'statcast': P.get('statcast'), 'statcast_vs': P.get('statcast_vs'),
                   'percentiles': p['percentiles'].get('pitching'), 'splits': P.get('splits'), 'postseason': P.get('postseason'), 'fip_constant': P.get('fip_constant')}
        parts += ['### pitching.summary', '```json', jdump(summary), '```', '',
                  '### pitching.arsenal (per pitch type; ivb/hb inches; rv_per_100 positive = good for pitcher)', '```json', jdump(P.get('arsenal')), '```', '',
                  '### pitching.arsenal_vs_hand', '```json', jdump(P.get('arsenal_vs')), '```', '',
                  '### pitching.zones', '```json', jdump(P.get('zones')), '```', '']
        types = [a['type'] for a in P.get('arsenal', [])]
        gl = []
        roll = {r['date']: r for r in P.get('rolling', {}).get('rows', [])}; cum = {r['date']: r for r in P.get('cumulative', [])}
        for g in P['gamelog']:
            sc = g.get('sc') or {}
            row = {'date': g['date'], 'gt': g['gt'], 'opp': g['opp'], 'home': int(bool(g['home'])), 'gs': g.get('gamesStarted'), 'dec': 'W' if g.get('wins') else 'L' if g.get('losses') else 'SV' if g.get('saves') else 'HLD' if g.get('holds') else '',
                   'ip': g.get('inningsPitched'), 'bf': g.get('battersFaced'), 'h': g.get('hits'), 'r': g.get('runs'), 'er': g.get('earnedRuns'), 'bb': g.get('baseOnBalls'), 'k': g.get('strikeOuts'),
                   'hr': g.get('homeRuns'), 'pitches': g.get('numberOfPitches'), 'whiffs': sc.get('whiffs'), 'called': sc.get('called'), 'swings': sc.get('swings'), 'xwoba_num': sc.get('xwoba_num'), 'woba_den': sc.get('woba_den')}
            for t in types:
                row[f'velo_{t}'] = (sc.get('velo') or {}).get(t); row[f'n_{t}'] = (sc.get('mix') or {}).get(t)
            if g['gt'] == 'R':
                row['cum_era'] = cum.get(g['date'], {}).get('era'); row['cum_fip'] = cum.get(g['date'], {}).get('fip'); row['roll_era'] = roll.get(g['date'], {}).get('era'); row['roll_k_pct'] = roll.get(g['date'], {}).get('k_pct')
            gl.append(row)
        cols = list(dict.fromkeys(k for r in gl for k in r))
        parts += [f'### pitching.gamelog (one row per outing; velo_<type> = avg mph that game; n_<type> = count; roll_* = rolling {P.get("rolling", {}).get("window_games")} games)', '```csv', csv_block(gl, cols), '```', '']
    parts += ['### fielding_running', '```json', jdump({'fielding': p['fielding'], 'running': p['running']}), '```', '',
              f'_Updated {TODAY} · sources: {"; ".join(p["sources"])}_', END]
    return '\n'.join(parts)

def tech_usm(p):
    parts = [START, '## Technical Stats — 2026', '',
             '> Machine-readable block for agents/infographics. Regenerated by the pipeline after every game — do not hand-edit between the markers.',
             f'> Full detail: `Data/players/{p["id"]}.json`. College data has no pitch tracking; pitch-sequence stats come from scorer ball/strike strings (B ball, K called strike, S swinging strike, F foul, X in play, H hit by pitch). Spray zones: LL/LF/LC/CF/RC/RF/RL outfield, 3B/IF-L/SS/IF-M/2B/IF-R/1B infield, P/C.', '']
    for side in ('hitting', 'pitching'):
        if side not in p: continue
        B = p[side]
        summ = {k: B.get(k) for k in ('season', 'plate_discipline', 'pitch_sequence', 'pbp', 'opponents_pbp', 'direction', 'results', 'splits') if B.get(k) is not None}
        parts += [f'### {side}.summary', '```json', jdump(summ), '```', '',
                  f'### {side}.spray_zones', '```json', jdump(B.get('spray') or B.get('spray_allowed')), '```', '',
                  f'### {side}.counts_pa_ended (count before final pitch)', '```json', jdump(B.get('counts_pa_ended')), '```', '']
        gl = B['gamelog']; cum = B['cumulative']; roll = B.get('rolling_10g') or B.get('rolling', {}).get('rows', [])
        rows = []
        for i, g in enumerate(gl):
            r = {k: v for k, v in g.items()}
            for k, v in (cum[i] if i < len(cum) else {}).items():
                if k != 'date': r['cum_' + k] = v
            for k, v in (roll[i] if i < len(roll) else {}).items():
                if k != 'date': r['roll_' + k] = v
            rows.append(r)
        cols = list(dict.fromkeys(k for r in rows for k in r))
        parts += [f'### {side}.gamelog (one row per game; cum_* season-to-date; roll_* rolling window)', '```csv', csv_block(rows, cols), '```', '',
                  f'### {side}.pa_log (every plate appearance: inning, result, field zone, batted-ball type, final count, pitch sequence, opposing hand)', '```csv',
                  csv_block(B['pa_log'], ['date', 'inn', 'res', 'zone', 'bbt', 'b', 's', 'seq', 'hand']), '```', '']
    parts += ['### fielding', '```json', jdump(p['fielding']), '```', '', f'_Updated {TODAY} · source: {"; ".join(p["sources"])}_', END]
    return '\n'.join(parts)

def profile_md(p):
    t = TEAM_DIR[p['team']]
    fm = {'type': 'player', 'name': p['name'], 'team': t, 'level': p['level'], 'season': 2026, 'number': p.get('number'), 'position': p.get('pos'), 'role': p['role'],
          'bats': p.get('bats'), 'throws': p.get('throws'), 'app_id': p['id']}
    if p['team'] == 'atl': fm.update({'mlbam_id': p['mlbam'], 'age': p.get('age'), 'birth_date': p.get('birth_date'), 'debut': p.get('debut'), 'status': p.get('status')})
    else: fm.update({'class': p.get('class'), 'hometown': p.get('hometown'), 'previous_school': p.get('previous_school')})
    fm['tags'] = ['player', p['team'], p['role']]
    y = '---\n' + '\n'.join(f'{k}: {json.dumps(v, ensure_ascii=False) if not isinstance(v, list) else "[" + ", ".join(v) + "]"}' for k, v in fm.items() if v is not None) + '\n---\n'
    lines = [f'# {p["name"]}', '', f'#{p.get("number") or "—"} · {p.get("pos_name") or p.get("pos")} · [[{t}/Roster|{t}]] · {p["level"]}', '']
    bio = [('Bats/Throws', f'{p.get("bats")}/{p.get("throws")}'), ('Height', p.get('height')), ('Weight', f'{p["weight"]} lb' if p.get('weight') else None)]
    bio += [('Age', p.get('age')), ('Born', p.get('birthplace')), ('MLB debut', p.get('debut'))] if p['team'] == 'atl' else [('Class', p.get('class')), ('Hometown', p.get('hometown')), ('High school', p.get('high_school')), ('Previous school', p.get('previous_school'))]
    lines += ['## Profile', ''] + [f'- **{k}:** {v}' for k, v in bio if v] + ['']
    lines += ['## 2026 at a glance', '']
    if 'hitting' in p and p['role'] != 'pitcher':
        h = p['hitting']
        if p['team'] == 'atl':
            s, sb, sc = h['season'], h.get('sabermetrics') or {}, h.get('statcast') or {}
            lines += ['| G | PA | AVG | OBP | SLG | HR | RBI | SB | wRC+ | WAR | xwOBA | Barrel% |', '|---|---|---|---|---|---|---|---|---|---|---|---|',
                      f'| {s.get("gamesPlayed")} | {s.get("plateAppearances")} | {fa(s.get("avg"))} | {fa(s.get("obp"))} | {fa(s.get("slg"))} | {s.get("homeRuns")} | {s.get("rbi")} | {s.get("stolenBases")} | {round(sb["wRcPlus"]) if sb.get("wRcPlus") is not None else "—"} | {round(sb["war"], 1) if sb.get("war") is not None else "—"} | {fa(sc.get("xwoba"))} | {pct(sc.get("barrel_pct"))} |']
        else:
            s = h['season']
            lines += ['| G | PA | AVG | OBP | SLG | HR | RBI | SB | OPS+ | wOBA | K% | BB% |', '|---|---|---|---|---|---|---|---|---|---|---|---|',
                      f'| {s["G"]} | {s["PA"]} | {fa(s["AVG"])} | {fa(s["OBP"])} | {fa(s["SLG"])} | {s["HR"]} | {s["RBI"]} | {s["SB"]} | {s["OPS+"] if s["OPS+"] is not None else "—"} | {fa(s["wOBA"])} | {pct(s["K%"])} | {pct(s["BB%"])} |']
        lines.append('')
    if 'pitching' in p:
        P = p['pitching']
        if p['team'] == 'atl':
            s, sb, sc = P['season'], P.get('sabermetrics') or {}, P.get('statcast') or {}
            lines += ['| G | GS | IP | W-L | SV | ERA | FIP | WHIP | K | K% | Whiff% | WAR |', '|---|---|---|---|---|---|---|---|---|---|---|---|',
                      f'| {s.get("gamesPlayed")} | {s.get("gamesStarted")} | {s.get("inningsPitched")} | {s.get("wins")}-{s.get("losses")} | {s.get("saves")} | {s.get("era")} | {round(sb["fip"], 2) if sb.get("fip") is not None else "—"} | {s.get("whip")} | {s.get("strikeOuts")} | {pct(sc.get("k_pct"))} | {pct(sc.get("whiff_pct"))} | {round(sb["war"], 1) if sb.get("war") is not None else "—"} |', '']
            if P.get('arsenal'):
                lines += ['**Arsenal:** ' + ' · '.join(f'{a["name"]} {pct(a["usage"])} ({a["velo"]} mph)' for a in P['arsenal']), '']
        else:
            s = P['season']
            lines += ['| G | GS | IP | W-L | SV | ERA | FIP | WHIP | K | K% | BB% | OPP AVG |', '|---|---|---|---|---|---|---|---|---|---|---|---|',
                      f'| {s["APP"]} | {s["GS"]} | {s["IP"]} | {s["W"]}-{s["L"]} | {s["SV"]} | {s["ERA"]} | {s["FIP"]} | {s["WHIP"]} | {s["K"]} | {pct(s["K%"])} | {pct(s["BB%"])} | {fa(s["OPP_AVG"])} |', '']
    lines += ['## Notes', '', '_Add your own notes here — this section is never overwritten._', '', '']
    tech = tech_atl(p) if p['team'] == 'atl' else tech_usm(p)
    return y + '\n'.join(lines) + tech + '\n'

