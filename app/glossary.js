window.gloss = function (k) {
  if (!k) return null;
  const g = window.GLOSSARY;
  if (g[k]) return g[k];
  const lk = String(k).toLowerCase();
  for (const key in g) if (key.toLowerCase() === lk) return g[key];
  return null;
};
